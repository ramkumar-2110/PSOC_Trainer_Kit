/*******************************************************************************
 * File Name: main.c
 *
 * Description:
 * Bare-metal Capacitive Touch Sensor
 *
 * Hardware:
 *     Touch Sensor -> P6_5
 *     LED1         -> P3_5
 *
 * Operation:
 *     Touch P6_5  -> LED1 ON
 *     Release     -> LED1 OFF
 *
 * Technique:
 *     Capacitive charge-decay measurement
 *******************************************************************************/

#include <stdint.h>
#include <stdbool.h>


/*******************************************************************************
 * P6 GPIO REGISTERS
 *******************************************************************************/

#define P6_DR       (*(volatile uint32_t *)0x40040600UL)
#define P6_PS       (*(volatile uint32_t *)0x40040604UL)
#define P6_PC       (*(volatile uint32_t *)0x40040608UL)
#define P6_PC2      (*(volatile uint32_t *)0x40040618UL)

#define P6_DR_SET   (*(volatile uint32_t *)0x40040640UL)
#define P6_DR_CLR   (*(volatile uint32_t *)0x40040644UL)


/*******************************************************************************
 * P3 GPIO REGISTERS
 *******************************************************************************/

#define P3_DR       (*(volatile uint32_t *)0x40040300UL)
#define P3_PC       (*(volatile uint32_t *)0x40040308UL)
#define P3_PC2      (*(volatile uint32_t *)0x40040318UL)

#define P3_DR_SET   (*(volatile uint32_t *)0x40040340UL)
#define P3_DR_CLR   (*(volatile uint32_t *)0x40040344UL)


/*******************************************************************************
 * HSIOM REGISTERS
 *******************************************************************************/

#define HSIOM_PORT_SEL3   (*(volatile uint32_t *)0x40020300UL)
#define HSIOM_PORT_SEL6   (*(volatile uint32_t *)0x40020600UL)


/*******************************************************************************
 * PIN DEFINITIONS
 *******************************************************************************/

#define TOUCH_PIN       5U
#define LED1_PIN        5U


/*******************************************************************************
 * GPIO DRIVE MODES
 *******************************************************************************/

/*
 * 0x01 = High-Z
 * 0x02 = Resistive Pull-Up
 * 0x03 = Resistive Pull-Down
 * 0x06 = Strong Drive
 */

#define GPIO_DM_PULLDOWN    0x03UL
#define GPIO_DM_STRONG      0x06UL


/*******************************************************************************
 * TOUCH CONFIGURATION
 *******************************************************************************/

#define TOUCH_THRESHOLD     16U
#define TOUCH_SAMPLES       64U
#define BASELINE_SAMPLES    16U
#define TOUCH_MAX_COUNT     1000U


/*******************************************************************************
 * GLOBAL VARIABLE
 *******************************************************************************/

static uint32_t g_baseline = 0;


/*******************************************************************************
 * DELAY IN MICROSECONDS
 *
 * Assumes approximately 48 MHz CPU clock.
 *******************************************************************************/

static void delay_us(uint32_t us)
{
    volatile uint32_t i;

    while (us--)
    {
        for (i = 0; i < 12U; i++)
        {
            __asm volatile ("nop");
        }
    }
}


/*******************************************************************************
 * TOUCH DRIVE MODE
 *
 * P6_5 drive mode field:
 *
 *     P6_5 -> PC bits 17:15
 *******************************************************************************/

static void touch_set_drive_mode(uint32_t mode)
{
    P6_PC &= ~(0x07UL << 15);
    P6_PC |=  ((mode & 0x07UL) << 15);

    /* Enable input buffer */
    P6_PC2 &= ~(1UL << TOUCH_PIN);
}


/*******************************************************************************
 * TOUCH RAW MEASUREMENT
 *
 * Charge P6_5 and measure its discharge time.
 *******************************************************************************/

static uint32_t touch_read_raw(void)
{
    uint32_t total = 0;
    uint32_t sample;

    for (sample = 0; sample < TOUCH_SAMPLES; sample++)
    {
        uint32_t count = 0;


        /***********************************************************************
         * STEP 1:
         * Configure P6_5 as strong output.
         ***********************************************************************/

        touch_set_drive_mode(GPIO_DM_STRONG);


        /***********************************************************************
         * STEP 2:
         * Charge touch sensor to HIGH.
         ***********************************************************************/

        P6_DR_SET = (1UL << TOUCH_PIN);


        /***********************************************************************
         * Allow capacitance to charge.
         ***********************************************************************/

        delay_us(5U);



        /***********************************************************************
         * Change P6_5 to resistive pull-down.
         ***********************************************************************/

        touch_set_drive_mode(GPIO_DM_PULLDOWN);


        /***********************************************************************
         * Start discharge.
         ***********************************************************************/

        P6_DR_CLR = (1UL << TOUCH_PIN);


        /***********************************************************************
         * STEP 4:
         * Count how long P6_5 remains HIGH.
         ***********************************************************************/

        while ((P6_PS & (1UL << TOUCH_PIN)) != 0U)
        {
            count++;

            if (count >= TOUCH_MAX_COUNT)
            {
                break;
            }
        }




        /***********************************************************************
         * Add measurement.
         ***********************************************************************/

        total += count;
    }

    return total;
}


/*******************************************************************************
 * TOUCH INITIALIZATION
 *******************************************************************************/

static void touch_init(void)
{
    uint32_t sum = 0;
    uint32_t i;


    /***************************************************************************
     * P6_5 -> GPIO
     *
     * HSIOM GPIO function = 0x0
     *
     * P6_5 -> HSIOM bits 23:20
     ***************************************************************************/

    HSIOM_PORT_SEL6 &= ~(0x0FUL << 20);


    /***************************************************************************
     * P6_5 -> Strong Drive
     ***************************************************************************/

    touch_set_drive_mode(GPIO_DM_STRONG);


    /***************************************************************************
     * Initially charge touch sensor
     ***************************************************************************/

    P6_DR_SET = (1UL << TOUCH_PIN);


    /***************************************************************************
     * Allow sensor to settle
     ***************************************************************************/

    delay_us(50U);


    /***************************************************************************
     * Calibrate baseline
     ***************************************************************************/

    for (i = 0; i < BASELINE_SAMPLES; i++)
    {
        sum += touch_read_raw();

        delay_us(10U);
    }

    g_baseline = sum / BASELINE_SAMPLES;
}


/*******************************************************************************
 * TOUCH DETECTION
 *******************************************************************************/

static bool touch_is_pressed(void)
{
    uint32_t raw;

    raw = touch_read_raw();


    /***************************************************************************
     * Touch increases capacitance.
     *
     * Increased capacitance:
     *      ↓
     * Slower discharge
     *      ↓
     * Larger count
     ***************************************************************************/

    if (raw > (g_baseline + TOUCH_THRESHOLD))
    {
        return true;
    }


    /***************************************************************************
     * Slowly track environmental changes.
     ***************************************************************************/

    g_baseline = ((g_baseline * 31U) + raw) / 32U;

    return false;
}


/*******************************************************************************
 * LED INITIALIZATION
 *
 * LED1 -> P3_5
 *******************************************************************************/

static void led_init(void)
{
    /***************************************************************************
     * P3_5 -> GPIO
     *
     * HSIOM bits 23:20
     ***************************************************************************/

    HSIOM_PORT_SEL3 &= ~(0x0FUL << 20);


    /***************************************************************************
     * P3_5 -> Strong Drive
     *
     * P3_5 drive mode -> PC bits 17:15
     ***************************************************************************/

    P3_PC &= ~(0x07UL << 15);
    P3_PC |=  (0x06UL << 15);


    /***************************************************************************
     * Enable input buffer
     ***************************************************************************/

    P3_PC2 &= ~(1UL << LED1_PIN);


    /***************************************************************************
     * LED initially OFF
     ***************************************************************************/

    P3_DR_CLR = (1UL << LED1_PIN);
}


void touch_app_init(void)
{
    led_init();
    touch_init();
}
void touch_app_run(void)
{
    bool touched;

    touched = touch_is_pressed();

    if (touched)
    {
        P3_DR_SET = (1UL << LED1_PIN);
    }
    else
    {
        P3_DR_CLR = (1UL << LED1_PIN);
    }
}
void touch_app_stop(void)
{
    P3_DR_CLR = (1UL << LED1_PIN);
}