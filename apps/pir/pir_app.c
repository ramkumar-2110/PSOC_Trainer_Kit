/*******************************************************************************
 * File Name: main.c
 *
 * Description:
 * Bare-metal PIR Motion Sensor application for PSoC 4.
 *
 * Hardware:
 *
 *     PIR Sensor OUT -> P2_0
 *     LED1           -> P3_5
 *
 * Operation:
 *
 *     Motion detected -> LED1 ON
 *     No motion       -> LED1 OFF
 *******************************************************************************/

#include <stdint.h>
#include "pir_app.h"


/*******************************************************************************
 * P2 GPIO REGISTERS
 *******************************************************************************/

#define P2_DR       (*(volatile uint32_t *)0x40040200UL)
#define P2_PS       (*(volatile uint32_t *)0x40040204UL)
#define P2_PC       (*(volatile uint32_t *)0x40040208UL)
#define P2_PC2      (*(volatile uint32_t *)0x40040218UL)


/*******************************************************************************
 * P3 GPIO REGISTERS
 *******************************************************************************/

#define P3_DR       (*(volatile uint32_t *)0x40040300UL)
#define P3_PC       (*(volatile uint32_t *)0x40040308UL)
#define P3_PC2      (*(volatile uint32_t *)0x40040318UL)

#define P3_DR_SET   (*(volatile uint32_t *)0x40040340UL)
#define P3_DR_CLR   (*(volatile uint32_t *)0x40040344UL)


/*******************************************************************************
 * HSIOM REGISTERS
 *******************************************************************************/

#define HSIOM_PORT_SEL2   (*(volatile uint32_t *)0x40020200UL)
#define HSIOM_PORT_SEL3   (*(volatile uint32_t *)0x40020300UL)


/*******************************************************************************
 * PIN DEFINITIONS
 *******************************************************************************/

#define PIR_PIN       0U
#define LED1_PIN      5U


/*******************************************************************************
 * GPIO DRIVE MODES
 *******************************************************************************/

#define GPIO_DM_HIGHZ     0x01UL
#define GPIO_DM_STRONG    0x06UL


/*******************************************************************************
 * PIR INITIALIZATION
 *******************************************************************************/

static void pir_init(void)
{
    /***************************************************************************
     * P2_0 -> GPIO
     *
     * P2_0 HSIOM bits = 3:0
     *
     * GPIO function = 0x0
     ***************************************************************************/

    HSIOM_PORT_SEL2 &= ~(0x0FUL << 0);


    /***************************************************************************
     * P2_0 -> High-Z input
     *
     * PIR module provides the digital output signal.
     ***************************************************************************/

    P2_PC &= ~(0x07UL << 0);
    P2_PC |=  (GPIO_DM_HIGHZ << 0);


    /***************************************************************************
     * Enable input buffer
     ***************************************************************************/

    P2_PC2 &= ~(1UL << PIR_PIN);
}


/*******************************************************************************
 * LED INITIALIZATION
 *******************************************************************************/

static void led_init(void)
{
    /***************************************************************************
     * P3_5 -> GPIO
     *
     * P3_5 HSIOM bits = 23:20
     ***************************************************************************/

    HSIOM_PORT_SEL3 &= ~(0x0FUL << 20);


    /***************************************************************************
     * P3_5 -> Strong Drive
     *
     * P3_5 drive mode = PC bits 17:15
     ***************************************************************************/

    P3_PC &= ~(0x07UL << 15);
    P3_PC |=  (GPIO_DM_STRONG << 15);


    /***************************************************************************
     * Enable input buffer
     ***************************************************************************/

    P3_PC2 &= ~(1UL << LED1_PIN);


    /***************************************************************************
     * LED initially OFF
     ***************************************************************************/

    P3_DR_CLR = (1UL << LED1_PIN);
}


/*******************************************************************************
 * MAIN
 *******************************************************************************/

void pir_app_init(void)
{
    /***************************************************************************
     * Initialize PIR sensor
     ***************************************************************************/

    pir_init();


    /***************************************************************************
     * Initialize LED
     ***************************************************************************/

    led_init();
}


    /***************************************************************************
     * Main loop
     ***************************************************************************/

void pir_app_run(void)
{
        /***********************************************************************
         * PIR output:
         *
         * HIGH -> Motion detected
         * LOW  -> No motion
         ***********************************************************************/

        if ((P2_PS & (1UL << PIR_PIN)) != 0U)
        {
            /* Motion detected */
            P3_DR_SET = (1UL << LED1_PIN);
        }
        else
        {
            /* No motion */
            P3_DR_CLR = (1UL << LED1_PIN);
        }
}
void pir_app_stop(void)
{
    P3_DR_CLR = (1UL << LED1_PIN);
}