/******************************************************************************
 * File Name:    joystick_app.c
 *
 * Description:
 * PSoC Trainer Kit - Joystick X-axis -> LED Direction Controller
 *
 * Target:
 * CY8C4147AZI-S475
 *
 * Joystick:
 *
 *     VRx -> P2_2
 *     VRy -> P2_3
 *     SW  -> P2_4
 *
 * LEDs:
 *
 *     LED1 -> P3_5
 *     LED2 -> P3_3
 *     LED3 -> P2_7
 *
 * Operation:
 *
 *     LEFT
 *         LED3 -> LED2 -> LED1
 *
 *     RIGHT
 *         LED1 -> LED2 -> LED3
 *
 *     CENTER
 *         All LEDs OFF
 *
 ******************************************************************************/

#include <stdint.h>
#include "joystick_app.h"


/******************************************************************************
 * GPIO REGISTERS
 ******************************************************************************/

#define P2_PC           (*(volatile uint32_t *)0x40040208UL)
#define P2_PC2          (*(volatile uint32_t *)0x40040218UL)

#define P2_DR_SET       (*(volatile uint32_t *)0x40040240UL)
#define P2_DR_CLR       (*(volatile uint32_t *)0x40040244UL)

#define P3_PC           (*(volatile uint32_t *)0x40040308UL)
#define P3_PC2          (*(volatile uint32_t *)0x40040318UL)

#define P3_DR_SET       (*(volatile uint32_t *)0x40040340UL)
#define P3_DR_CLR       (*(volatile uint32_t *)0x40040344UL)


/******************************************************************************
 * HSIOM REGISTERS
 ******************************************************************************/

#define HSIOM_PORT_SEL2     (*(volatile uint32_t *)0x40020200UL)
#define HSIOM_PORT_SEL3     (*(volatile uint32_t *)0x40020300UL)


/******************************************************************************
 * PERIPHERAL CLOCK REGISTERS
 ******************************************************************************/

#define PERI_DIV_CMD        (*(volatile uint32_t *)0x40010000UL)

#define PERI_DIV_8_CTL0     (*(volatile uint32_t *)0x40010200UL)

#define PERI_DIV_16_CTL0    (*(volatile uint32_t *)0x40010300UL)


/******************************************************************************
 * SAR ADC REGISTERS
 ******************************************************************************/

#define SAR_CTRL                (*(volatile uint32_t *)0x403A0000UL)

#define SAR_SAMPLE_CTRL         (*(volatile uint32_t *)0x403A0004UL)

#define SAR_SAMPLE_TIME01       (*(volatile uint32_t *)0x403A0010UL)

#define SAR_CHAN_EN             (*(volatile uint32_t *)0x403A0020UL)

#define SAR_START_CTRL          (*(volatile uint32_t *)0x403A0024UL)

#define SAR_CHAN_CONFIG1        (*(volatile uint32_t *)0x403A0084UL)

#define SAR_CHAN_RESULT1        (*(volatile uint32_t *)0x403A0184UL)

#define SAR_CHAN_RESULT_VALID   (*(volatile uint32_t *)0x403A0204UL)

#define SAR_MUX_SWITCH0         (*(volatile uint32_t *)0x403A0300UL)

/*
 * Correct CLEAR register for SAR_MUX_SWITCH0.
 */
#define SAR_MUX_SWITCH_CLEAR0   (*(volatile uint32_t *)0x403A0304UL)

#define SAR_MUX_SWITCH_HW       (*(volatile uint32_t *)0x403A0340UL)


/******************************************************************************
 * SYSTICK REGISTERS
 ******************************************************************************/

#define SYST_CSR                (*(volatile uint32_t *)0xE000E010UL)

#define SYST_RVR                (*(volatile uint32_t *)0xE000E014UL)

#define SYST_CVR                (*(volatile uint32_t *)0xE000E018UL)


/******************************************************************************
 * CLOCK
 ******************************************************************************/

#define IMO_HZ                  24000000UL


/******************************************************************************
 * PIN DEFINITIONS
 ******************************************************************************/

#define JOYSTICK_X_PIN         2U

#define LED1_PIN               5U

#define LED2_PIN               3U

#define LED3_PIN               7U


/******************************************************************************
 * JOYSTICK THRESHOLDS
 ******************************************************************************/

#define JOYSTICK_LEFT_LIMIT    1500UL

#define JOYSTICK_RIGHT_LIMIT   2600UL


/******************************************************************************
 * DELAY FUNCTION
 ******************************************************************************/

static void delay_ms(uint32_t ms)
{
    while (ms--)
    {
        SYST_RVR = (IMO_HZ / 1000UL) - 1U;

        SYST_CVR = 0U;

        SYST_CSR = 0x05U;

        while ((SYST_CSR & (1UL << 16U)) == 0UL)
        {
        }

        SYST_CSR = 0U;
    }
}


/******************************************************************************
 * LED INITIALIZATION
 ******************************************************************************/

static void led_init(void)
{
    /**************************************************************************
     * LED1 -> P3_5
     **************************************************************************/

    HSIOM_PORT_SEL3 &= ~(0x0FUL << 20U);

    P3_PC &= ~(0x07UL << 15U);
    P3_PC |= (6UL << 15U);

    P3_PC2 &= ~(1UL << LED1_PIN);

    P3_DR_CLR = (1UL << LED1_PIN);


    /**************************************************************************
     * LED2 -> P3_3
     **************************************************************************/

    HSIOM_PORT_SEL3 &= ~(0x0FUL << 12U);

    P3_PC &= ~(0x07UL << 9U);
    P3_PC |= (6UL << 9U);

    P3_PC2 &= ~(1UL << LED2_PIN);

    P3_DR_CLR = (1UL << LED2_PIN);


    /**************************************************************************
     * LED3 -> P2_7
     **************************************************************************/

    HSIOM_PORT_SEL2 &= ~(0x0FUL << 28U);

    P2_PC &= ~(0x07UL << 21U);
    P2_PC |= (6UL << 21U);

    P2_PC2 &= ~(1UL << LED3_PIN);

    P2_DR_CLR = (1UL << LED3_PIN);
}


/******************************************************************************
 * ALL LEDs OFF
 ******************************************************************************/

static void leds_off(void)
{
    P3_DR_CLR = (1UL << LED1_PIN);

    P3_DR_CLR = (1UL << LED2_PIN);

    P2_DR_CLR = (1UL << LED3_PIN);
}


/******************************************************************************
 * LED1 ON
 ******************************************************************************/

static void led1_on(void)
{
    leds_off();

    P3_DR_SET = (1UL << LED1_PIN);
}


/******************************************************************************
 * LED2 ON
 ******************************************************************************/

static void led2_on(void)
{
    leds_off();

    P3_DR_SET = (1UL << LED2_PIN);
}


/******************************************************************************
 * LED3 ON
 ******************************************************************************/

static void led3_on(void)
{
    leds_off();

    P2_DR_SET = (1UL << LED3_PIN);
}


/******************************************************************************
 * ADC INITIALIZATION
 ******************************************************************************/

static void adc_init(void)
{
    /**************************************************************************
     * 1. Stop previous SAR operation
     **************************************************************************/

    SAR_START_CTRL = 0U;

    SAR_CHAN_EN = 0U;


    /**************************************************************************
     * 2. Clear previous SARMUX firmware connections
     *
     * P2_1 = bit 1
     * P2_2 = bit 2
     **************************************************************************/

    SAR_MUX_SWITCH_CLEAR0 = 0xFFFFFFFFUL;


    /**************************************************************************
     * 3. Clear previous channel configuration
     **************************************************************************/

    SAR_CHAN_CONFIG1 = 0U;


    /**************************************************************************
     * 4. Configure P2_2 as analog input
     *
     * P2_2 -> AMUXA
     **************************************************************************/

    HSIOM_PORT_SEL2 &= ~(0x0FUL << 8U);

    HSIOM_PORT_SEL2 |= (6UL << 8U);


    /*
     * Analog High-Z
     */
    P2_PC &= ~(0x07UL << 6U);


    /*
     * Disable digital input buffer.
     */
    P2_PC2 |= (1UL << JOYSTICK_X_PIN);


    /**************************************************************************
     * 5. Configure SAR clock
     *
     * IMO = 24 MHz
     * SAR clock = 1 MHz
     **************************************************************************/

    PERI_DIV_16_CTL0 = (23UL << 8U);

    PERI_DIV_CMD =
          (1UL << 31U)
        | (0x3UL << 14U)
        | (0x3FUL << 8U)
        | (1UL << 6U);


    PERI_DIV_8_CTL0 = (23UL << 8U);

    PERI_DIV_CMD =
          (1UL << 31U)
        | (0x3UL << 14U)
        | (0x3FUL << 8U)
        | (1UL << 6U);


    /**************************************************************************
     * 6. Route SAR clock
     *
     * This is the known working SAR PCLK slot.
     **************************************************************************/

    (*(volatile uint32_t *)0x40010148UL) = (1UL << 6U);


    /**************************************************************************
     * 7. Configure SAR
     **************************************************************************/

    SAR_CTRL =
          (1UL << 31U)
        | (7UL << 4U)
        | (0UL << 9U);


    delay_ms(10U);


    /**************************************************************************
     * 8. Sample time
     **************************************************************************/

    SAR_SAMPLE_TIME01 = 128UL;


    /**************************************************************************
     * 9. Continuous conversion
     **************************************************************************/

    SAR_SAMPLE_CTRL = (1UL << 16U);


    /**************************************************************************
     * 10. Configure channel 1
     *
     * P2_2 -> VPLUS1
     **************************************************************************/

    SAR_CHAN_CONFIG1 = 2UL;


    /**************************************************************************
     * 11. Enable channel 1
     **************************************************************************/

    SAR_CHAN_EN = (1UL << 1U);


    /**************************************************************************
     * 12. Connect P2_2 to SARMUX
     **************************************************************************/

    SAR_MUX_SWITCH_HW = (1UL << 2U);

    SAR_MUX_SWITCH0 = (1UL << 2U);


    /**************************************************************************
     * 13. Start conversion
     **************************************************************************/

    SAR_START_CTRL = 1UL;
}


/******************************************************************************
 * JOYSTICK ADC READ
 ******************************************************************************/

static uint32_t joystick_x_read(void)
{
    uint32_t raw;

    /*
     * Wait for channel 1 result.
     */
    while ((SAR_CHAN_RESULT_VALID & (1UL << 1U)) == 0UL)
    {
    }

    raw = SAR_CHAN_RESULT1 & 0x0FFFUL;

    /*
     * Convert signed ADC result.
     */
    raw ^= 0x800UL;

    return raw;
}


/******************************************************************************
 * APPLICATION INITIALIZATION
 ******************************************************************************/

void joystick_app_init(void)
{
    led_init();

    adc_init();

    leds_off();
}


/******************************************************************************
 * APPLICATION RUN
 ******************************************************************************/

void joystick_app_run(void)
{
    uint32_t x;

    x = joystick_x_read();


    /**************************************************************************
     * LEFT
     **************************************************************************/

    if (x < JOYSTICK_LEFT_LIMIT)
    {
        /*
         * LED3 -> LED2 -> LED1
         */

        led3_on();

        delay_ms(500U);

        led2_on();

        delay_ms(500U);

        led1_on();

        delay_ms(500U);
    }


    /**************************************************************************
     * RIGHT
     **************************************************************************/

    else if (x > JOYSTICK_RIGHT_LIMIT)
    {
        /*
         * LED1 -> LED2 -> LED3
         */

        led1_on();

        delay_ms(500U);

        led2_on();

        delay_ms(500U);

        led3_on();

        delay_ms(500U);
    }


    /**************************************************************************
     * CENTER
     **************************************************************************/

    else
    {
        leds_off();

        delay_ms(200U);
    }
}


/******************************************************************************
 * APPLICATION STOP
 ******************************************************************************/

void joystick_app_stop(void)
{
    /*
     * Turn LEDs OFF.
     */
    leds_off();
}